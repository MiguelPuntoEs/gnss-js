/**
 * US State Plane Coordinate System of 1983 (SPCS83) on NAD83(2011), metre
 * zones: the 117 transverse Mercator and Lambert conformal conic zones,
 * parameters and areas of use as EPSG registers them (generated from PROJ
 * 9.8.1's database). Alaska zone 1 (oblique Mercator) is not included,
 * nor Hawaii and the Pacific islands, which are on NAD83(PA11)/(MA11).
 * Many states legislate feet: multiply by 1200/3937 (US survey foot) or
 * 0.3048 (international foot) to go from feet to metres.
 */
