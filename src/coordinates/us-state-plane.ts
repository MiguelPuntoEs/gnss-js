/**
 * The zone for a point: the smallest EPSG area of use containing it
 * (areas of neighbouring states overlap; the official zone follows county
 * lines). Undefined outside them all.
 */
export function statePlaneZoneAt(
  latDeg: number,
  lonDeg: number
): StatePlaneZone | undefined {
  let best: StatePlaneZone | undefined;
  let bestArea = Infinity;
  for (const z of US_STATE_PLANE_ZONES) {
    const [w, s, e, n] = z.bbox;
    // Alaska zone 10 crosses the antimeridian (w > e).
    const inLon =
      w <= e ? lonDeg >= w && lonDeg <= e : lonDeg >= w || lonDeg <= e;
    if (latDeg < s || latDeg > n || !inLon) continue;
    const area = ((e - w + 360) % 360) * (n - s);
    if (area < bestArea) {
      best = z;
      bestArea = area;
    }
  }
  return best;
}
