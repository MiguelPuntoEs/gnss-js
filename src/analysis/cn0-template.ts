export interface Cn0Check {
  /** Median over signals of (file − reference) above 30°, dB. */
  deficitDb: number;
  perSignal: { key: string; label: string; deltaDb: number; n: number }[];
}

/**
 * Compare a file's C/N0-vs-elevation with {@link CN0_TEMPLATE} above 30°.
 * Semi-codeless P(Y) ("W") and SBAS signals are left out (receiver-specific
 * and GEO-only). Null when fewer than two signals can be compared.
 */
export function compareCn0WithTemplate(
  rows: readonly {
    system: string;
    code: string;
    label: string;
    mean: (number | null)[];
    n: number[];
  }[]
): Cn0Check | null {
  const perSignal: Cn0Check['perSignal'] = [];
  for (const r of rows) {
    if (r.system === 'S' || r.code[2] === 'W') continue;
    const t = CN0_TEMPLATE[`${r.system}:${r.code}`];
    if (!t) continue;
    let sum = 0;
    let n = 0;
    for (let k = 30 / CN0_TEMPLATE_BIN_DEG; k < r.mean.length; k++) {
      const m = r.mean[k];
      const ref = t.median[k];
      const cnt = r.n[k] ?? 0;
      if (m == null || ref == null || cnt < 20) continue;
      sum += (m - ref) * cnt;
      n += cnt;
    }
    if (n > 0)
      perSignal.push({
        key: `${r.system}:${r.code}`,
        label: r.label,
        deltaDb: sum / n,
        n,
      });
  }
  if (perSignal.length < 2) return null;
  const d = perSignal.map((p) => p.deltaDb).sort((a, b) => a - b);
  const mid = Math.floor(d.length / 2);
  return {
    deficitDb: d.length % 2 ? d[mid]! : (d[mid - 1]! + d[mid]!) / 2,
    perSignal,
  };
}
