describe('IGRF-14 synthesis', () => {
  it('matches an independent implementation to < 1 nT', () => {
    for (const [t, lat, lon, h, n, e, dn] of ORACLE) {
      const b = igrfField(lat * D2R, lon * D2R, h * 1000, Date.parse(t));
      expect(Math.abs(b.north - n), `${t} ${lat} ${lon} N`).toBeLessThan(1);
      expect(Math.abs(b.east - e), `${t} ${lat} ${lon} E`).toBeLessThan(1);
      expect(Math.abs(b.down - dn), `${t} ${lat} ${lon} D`).toBeLessThan(1);
      expect(Math.hypot(...b.ecef)).toBeCloseTo(Math.hypot(n, e, dn), 0);
    }
  });
  it('ECEF vector agrees with the local components', () => {
    const lat = 49.1442 * D2R;
    const lon = 12.8789 * D2R;
    const b = igrfField(lat, lon, 0, Date.UTC(2024, 0, 8));
    const up = [
      Math.cos(lat) * Math.cos(lon),
      Math.cos(lat) * Math.sin(lon),
      Math.sin(lat),
    ];
    const dot = b.ecef[0] * up[0]! + b.ecef[1] * up[1]! + b.ecef[2] * up[2]!;
    expect(-dot).toBeCloseTo(b.down, 0);
  });
});
