describe('RINEX 3 nav: transmission time, accuracy, data sources', () => {
  const eph = parseNavFile(NAV).ephemerides as KeplerEphemeris[];
  const by = (p: string) => eph.find((e) => e.prn === p)!;

  it('GPS: URA and a negative (previous-week) transmission time', () => {
    expect(by('G05').svAccuracy).toBe(2);
    expect(by('G05').ttm).toBe(-1074);
    expect(by('G05').tgd2).toBeUndefined();
  });

  it('Galileo: SISA, F/NAV data source, both BGDs', () => {
    const e = by('E11');
    expect(e.svAccuracy).toBeCloseTo(3.12);
    expect(e.dataSources).toBe(258); // F/NAV, clock for E5a/E1
    expect(e.tgd).toBeCloseTo(-1.58324837685e-8, 18);
    expect(e.tgd2).toBe(0);
    expect(e.ttm).toBe(604320);
  });

  it('BeiDou: URA, TGD1 and TGD2', () => {
    const e = by('C30');
    expect(e.svAccuracy).toBe(2);
    expect(e.tgd).toBeCloseTo(-9.6999999144e-9, 18);
    expect(e.tgd2).toBeCloseTo(-9.7e-9, 18);
    expect(e.ttm).toBe(0);
  });
});
